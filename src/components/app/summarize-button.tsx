"use client";

import { useState } from "react";
import { toast } from "sonner";
import { SparkleIcon, CopyIcon, CheckIcon } from "@phosphor-icons/react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Skeleton } from "@/components/ui/skeleton";
import {
  summarizeDocument,
  type SummarizeResult,
} from "@/app/(app)/ai-actions";
import { parseSummaryBullets, bulletsToText } from "@/lib/ai/format-summary";

type SummarizeButtonProps = {
  documentId: string;
  disabled?: boolean;
};

export function SummarizeButton({
  documentId,
  disabled = false,
}: SummarizeButtonProps) {
  const [open, setOpen] = useState(false);
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<SummarizeResult | null>(null);
  const [copied, setCopied] = useState(false);

  async function run() {
    setOpen(true);
    setLoading(true);
    setResult(null);
    setCopied(false);
    try {
      setResult(await summarizeDocument(documentId));
    } catch {
      setResult({
        ok: false,
        error:
          "Couldn't reach the server. Check your connection and try again.",
      });
    } finally {
      setLoading(false);
    }
  }

  async function copy(text: string) {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error("Couldn't copy to the clipboard.");
    }
  }

  const bullets = result?.ok ? parseSummaryBullets(result.summary) : [];

  return (
    <>
      <Button
        variant="outline"
        size="sm"
        onClick={run}
        disabled={disabled || loading}
        title={disabled ? "Wait for your changes to finish saving" : undefined}
      >
        <SparkleIcon className="size-4" />
        Summarize
      </Button>

      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="sm:max-w-lg">
          <DialogHeader>
            <DialogTitle>Summary</DialogTitle>
            <DialogDescription>
              Generated by AI from your last saved version. The document text is
              sent to Google&apos;s Gemini service, and the summary may contain
              mistakes.
            </DialogDescription>
          </DialogHeader>

          {loading && (
            <div className="space-y-2" aria-busy="true">
              <Skeleton className="h-4 w-full" />
              <Skeleton className="h-4 w-11/12" />
              <Skeleton className="h-4 w-10/12" />
              <Skeleton className="h-4 w-9/12" />
            </div>
          )}

          {!loading && result && !result.ok && (
            <div className="space-y-3">
              <p className="text-sm text-destructive" role="alert">
                {result.error}
              </p>
              <Button variant="outline" size="sm" onClick={run}>
                Try again
              </Button>
            </div>
          )}

          {!loading && result?.ok && (
            <div className="space-y-4">
              <ul className="list-disc space-y-2 pl-5 text-sm">
                {bullets.map((bullet, index) => (
                  <li key={index}>{bullet}</li>
                ))}
              </ul>
              {result.truncated && (
                <p className="text-xs text-muted-foreground">
                  This document is very long, so only the first part was
                  summarized.
                </p>
              )}
              <Button
                variant="outline"
                size="sm"
                onClick={() => copy(bulletsToText(bullets))}
              >
                {copied ? (
                  <CheckIcon className="size-4" />
                ) : (
                  <CopyIcon className="size-4" />
                )}
                {copied ? "Copied" : "Copy"}
              </Button>
            </div>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
